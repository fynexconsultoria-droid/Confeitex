  _detect() {
    try {
      const nav = (navigator.language || this.defaultLang).toLowerCase();
      if (nav.indexOf('pt') === 0) return 'pt-BR';
      if (nav.indexOf('en') === 0) return 'en';
    } catch (e) {}
    return this.defaultLang;
  },

  get lang() {
    let l = null;
    try { l = safeStorage.get(this.storageKey); } catch (e) {}
    if (!l || this.codes.indexOf(l) === -1) l = this._detect();
    return l;
  },

  locale() {
    return this.locales[this.lang] || this.defaultLang;
  },

  currency() {
    return this.currencies[this.lang] || 'BRL';
  },

  currencySymbol() {
    const s = { BRL: 'R$', USD: '$', EUR: '€' }[this.currency()] || 'R$';
    return s;
  },

  setLang(code) {
    if (this.codes.indexOf(code) === -1) return this.lang;
    try { safeStorage.set(this.storageKey, code); } catch (e) {}
    this.apply();
    document.documentElement.lang = code;
    if (typeof this.onApply === 'function') {
      try { this.onApply(code); } catch (e) { console.warn('[I18n] onApply error:', e); }
    }
    return code;
  },

  t(key, vars) {
    let s = (this.dict[this.lang] && this.dict[this.lang][key])
      || this.dict[this.defaultLang][key]
      || key;
    if (vars) {
      for (const k in vars) {
        s = s.split('{' + k + '}').join(String(vars[k]));
      }
    }
    return s;
  },

  // Traduz um valor persistido em português (status, pagamento, etc.)
  value(type, v) {
    if (v === null || v === undefined || v === '') return v;
    const key = type + '.' + v;
    const s = this.dict[this.lang] && this.dict[this.lang][key];
    return s || v;
  },

  apply() {
    const lang = this.lang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = this.t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      el.placeholder = this.t(el.dataset.i18nPh);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = this.t(el.dataset.i18nTitle);
    });
    document.querySelectorAll('[data-i18n-opt]').forEach(opt => {
      opt.textContent = this.t(opt.dataset.i18nOpt);
    });
    document.documentElement.lang = lang;
    document.title = this.t('meta.title');
  }
